/* Uzbek, in the Latin alphabet. Oʻ and gʻ are written with ‘ (U+2018) and
 * the tutuq belgisi with ’ (U+2019) rather than the modifier letters: every
 * font on the page has these two, and not all of them have ʻ and ʼ.
 *
 * Case endings attach straight to a player's name. They do not change with
 * the word, except the dative, which does after k/g and q/gʻ - hence `dat`. */

const dat = (name: string): string => {
  const w = name.trim().toLowerCase();
  if (w.endsWith('g‘') || w.endsWith('q')) return `${name}qa`;
  if (w.endsWith('k') || w.endsWith('g')) return `${name}ka`;
  return `${name}ga`;
};

