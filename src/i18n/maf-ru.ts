/* Russian for Omertà. As in cf-ru.ts, sentences avoid the past tense so a
 * verb never has to guess a player's gender, and player names stay in the
 * nominative. The game name stays as-is, like Nest Egg and Bazaar Barons. */

const pl = (n: number, one: string, few: string, many: string): string => {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
};

