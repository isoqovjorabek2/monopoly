/* Russian. Log lines are in the present tense on purpose: the past tense
 * agrees with the speaker's gender ("заплатил" / "заплатила"), and a player
 * name says nothing reliable about that. Likewise "игроку X" keeps a name in
 * the nominative instead of guessing how it declines. */

/** Russian plural: 1 правило, 2 правила, 5 правил. */
const pl = (n: number, one: string, few: string, many: string): string => {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
};

